// Возвращает случайную цитату из локального набора
async function getRandomQuote(bookId) {
    const quotes = LOCAL_QUOTES[bookId];
    if (!quotes || quotes.length === 0) return "Цитаты не найдены";
    return quotes[Math.floor(Math.random() * quotes.length)];
}

// Возвращает другую случайную цитату, не совпадающую с текущей
function refreshQuote(bookId) {
    const quotes = LOCAL_QUOTES[bookId];
    if (!quotes || quotes.length === 0) return null;
    if (quotes.length === 1) return quotes[0];
    return quotes[Math.floor(Math.random() * quotes.length)];
}
